const { Registry } = require("../game.js");
let failed = 0;
const check = (name, cond) => { console.log(cond ? "OK  " : "FAIL", name); if (!cond) failed++; };
const attempt = (fn) => { try { fn(); return true; } catch (e) { return e.message; } };
const reg = new Registry();
const room = reg.createRoom();
const ps = ["Ania", "Bartek", "Celina", "Darek"].map((nick) => { const p = room.addPlayer(nick); p.connected = true; return p; });
room.setMode(ps[0], "piec");
room.start(ps[0]);
const asker = room.getPlayer(room.five.askerId);
const target = room.players.find((p) => p !== asker);
const other = room.players.find((p) => p !== asker && p !== target);
const caster = room.players.find((p) => p !== asker && p !== target && p !== other);
caster.cards = [{ id: 900, type: "english" }, { id: 901, type: "torpedo" }];
room.fivePlayCard(caster, 900, target.id);
room.fivePlayCard(caster, 901, target.id);
check("torpedo forces target", room.five.answererId === target.id && room.five.stage === "ready");
check("curses on question", room.five.curses.includes("english") && room.five.stake === 2);
check("redo blocked before start", attempt(() => room.fiveRedo(asker)) !== true);
const t1 = room.five.task.text;
room.fiveStart(asker);
check("non-asker cannot redo", attempt(() => room.fiveRedo(other)) !== true);
check("redo button visible in view", room.viewFor(asker).five.redone === false);
const livesBefore = target.lives;
const hist = room.fiveHistory.length;
room.fiveRedo(asker);
check("back to ready, same duel", room.five.stage === "ready" && room.five.askerId === asker.id && room.five.answererId === target.id);
check("new task, hidden from others", room.five.task.text !== t1 && room.viewFor(target).five.task === null);
check("curses and stake kept", room.five.curses.includes("english") && room.five.stake === 2);
check("no vote, no lives lost, no history", target.lives === livesBefore && room.fiveHistory.length === hist && room.five.votes.size === 0);
check("timer cleared", room.five.timer === null && room.five.endsAt === 0);
room.fiveStart(asker);
check("second redo blocked", attempt(() => room.fiveRedo(asker)) !== true);
room.fiveForceNext();
check("vote stage", room.five.stage === "vote");
for (const p of room.players) if (room.five.stage === "vote" && p !== target) room.fiveVote(p, false);
check("failure costs torpedo stake 2", target.lives === livesBefore - 2);
const a2 = room.getPlayer(room.five.askerId);
const t2 = room.players.find((p) => p !== a2 && p.lives > 0);
room.fiveChoose(a2, t2.id);
room.fiveStart(a2);
room.fiveForceNext();
check("fresh question allows redo again, also in vote", room.five.redone === false && attempt(() => room.fiveRedo(ps[0])) === true && room.five.stage === "ready");
console.log(failed ? "FAILED" : "ALL PASSED");
process.exit(failed ? 1 : 0);

const { io } = require("socket.io-client");
const U = "http://localhost:3505";
const mk = () => {
  const s = io(U, { transports: ["websocket"] });
  s.msgs = [];
  s.raw = [];
  s.on("chat:message", (m) => s.msgs.push(m));
  s.on("chat:history", (h) => (s.history = h));
  s.onAny((event, payload) => s.raw.push(JSON.stringify(payload || "")));
  s.on("state", (st) => (s.st = st));
  s.req = (e, p = {}) => new Promise((r) => s.emit(e, p, r));
  return s;
};
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
let failed = 0;
const check = (name, cond) => { console.log(cond ? "OK  " : "FAIL", name); if (!cond) failed++; };
(async () => {
  const a = mk(), b = mk(), c = mk();
  await wait(300);
  const ra = await a.req("createRoom", { nick: "Ania" });
  await wait(100);
  const code = a.st.code;
  await b.req("joinRoom", { nick: "Bartek", code });
  await c.req("joinRoom", { nick: "Celina", code });
  const w = (n) => Array.from({ length: 10 }, (_, i) => n + "Haslo" + i);
  await a.req("setWords", { words: w("Ala") });
  await b.req("setWords", { words: w("Bob") });
  await c.req("setWords", { words: w("Cyd") });
  check("lobby public chat ok", (await a.req("chat:send", { text: "cześć wszystkim" })).ok);
  await wait(80);
  check("all received public", b.msgs.length === 1 && c.msgs.length === 1);
  await wait(400);
  check("private ok", (await a.req("chat:send", { text: "psst tylko ty", toId: b.st.me.id })).ok);
  await wait(80);
  check("B got private", b.msgs.some((m) => m.text === "psst tylko ty"));
  check("C did not get private", !c.msgs.some((m) => m.text === "psst tylko ty") && !c.raw.some((r) => r.includes("psst")));
  check("spam blocked", !(await a.req("chat:send", { text: "spam" })).ok);
  await a.req("startGame");
  await wait(150);
  const bWord = a.st.players.find((p) => p.id === b.st.me.id).word;
  await wait(400);
  await a.req("chat:send", { text: "Bartek ma " + bWord + " hehe" });
  await wait(100);
  const bLast = b.msgs[b.msgs.length - 1];
  const cLast = c.msgs[c.msgs.length - 1];
  check("C sees word in chat", cLast.text.includes(bWord));
  check("B gets masked word", !bLast.text.includes(bWord) && bLast.text.includes("█"));
  check("B raw socket never contains own word", !b.raw.some((r) => r.includes(bWord)));
  b.disconnect();
  const b2 = mk();
  await wait(300);
  const token = null;
  const c2history = c.history;
  check("C history had only public at join", Array.isArray(c2history));
  const resumed = mk();
  await wait(300);
  await resumed.req("resume", { token: ra.token });
  await wait(150);
  check("resume gives history incl. own private", resumed.history.length === 3 && resumed.history.some((m) => m.toId));
  const tooBig = await a.req("chat:send", { image: "data:image/png;base64," + "A".repeat(470000) });
  check("oversized image rejected", !tooBig.ok);
  console.log(failed ? failed + " FAILED" : "ALL PASSED");
  process.exit(failed ? 1 : 0);
})();

const { Registry } = require("../game.js");
let failed = 0;
const check = (name, cond) => { console.log(cond ? "OK  " : "FAIL", name); if (!cond) failed++; };
const attempt = (fn) => { try { fn(); return true; } catch (e) { return e.message; } };
const reg = new Registry();
const room = reg.createRoom();
const ps = ["Ania", "Bartek", "Celina"].map((n) => { const p = room.addPlayer(n); p.connected = true; return p; });
room.setMode(ps[0], "piec");
room.setSetting(ps[0], "fiveRerolls", 2);
room.setFiveTasks(ps[1], ["Wymień trzy wspólne zadanie testowe"]);
room.setFiveTasks(ps[2], ["wymień trzy wspólne zadanie testowe!"]);
room.setSetting(ps[0], "fiveOwnChance", 100);
room.start(ps[0]);
const asker = room.getPlayer(room.five.askerId);
const target = ps.find((p) => p.id !== asker.id);
room.fiveChoose(asker, target.id);
check("shared task has 2 authors", room.five.task.authorIds.length === 2);
check("taskAuthor joined", room.fiveView(asker).taskAuthor === "Bartek i Celina");
const view = () => room.viewFor(asker).players.find((p) => p.id === asker.id).rerollsLeft;
check("left 2", view() === 2);
check("others don't see", room.viewFor(target).players.find((p) => p.id === asker.id).rerollsLeft === null);
room.fiveReroll(asker); room.fiveReroll(asker);
check("left 0", view() === 0);
check("3rd blocked", String(attempt(() => room.fiveReroll(asker))).includes("Wykorzystałeś"));
room.setSetting(ps[0], "fiveRerolls", 99);
check("unlimited null", view() === null && attempt(() => room.fiveReroll(asker)) === true);
room.setSetting(ps[0], "fiveRerolls", 0);
check("disabled msg", String(attempt(() => room.fiveReroll(asker))).includes("wyłączona"));

const r2 = reg.createRoom();
const qs = ["Ala", "Bob", "Cyryl"].map((n) => { const p = r2.addPlayer(n); p.connected = true; return p; });
const BASE = ["Pomarańcza", "Hulajnoga", "Kaloryfer", "Teleskop", "Wiewiórka", "Parasol", "Krokodyl", "Ołówek", "Mikrofon"];
qs.forEach((p, i) => r2.setWords(p, [["Arteta", "artera", "ARTETA"][i], ...BASE.map((w) => p.nick + " " + w)]));
r2.start(qs[0]);
const all = [...r2.pool, ...r2.players.map((p) => p.word).filter(Boolean)];
const art = all.find((w) => /art/i.test(w.text));
check("czolko 3 authors", r2.authorName(art) === "Ala, Bob i Cyryl");
console.log(failed ? failed + " FAILED" : "ALL OK");
process.exit(failed ? 1 : 0);

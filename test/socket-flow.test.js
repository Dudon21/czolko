const { io } = require("socket.io-client");
const URL = "http://localhost:3505";
const words = (p) => Array.from({ length: 10 }, (_, i) => `${p}-slowo-${i}`);
function client() {
  const s = io(URL, { transports: ["websocket"] });
  s.last = null;
  s.on("state", (st) => (s.last = st));
  s.req = (e, p = {}) => new Promise((r) => s.emit(e, p, r));
  return s;
}
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
let failed = 0;
function check(name, cond) {
  console.log(cond ? "OK  " : "FAIL", name);
  if (!cond) failed++;
}
(async () => {
  const a = client(), b = client(), c = client();
  await wait(300);
  const created = await a.req("createRoom", { nick: "A" });
  await wait(100);
  const code = a.last.code;
  await b.req("joinRoom", { nick: "B", code });
  await c.req("joinRoom", { nick: "C", code });
  for (const [s, n] of [[a, "A"], [b, "B"], [c, "C"]]) await s.req("setWords", { words: words(n) });
  check("default helpLimit 1", a.last.helpLimit === 1);
  check("non-host cannot set help limit", !(await b.req("setHelpLimit", { limit: 2 })).ok);
  check("host sets help limit 2", (await a.req("setHelpLimit", { limit: 2 })).ok);
  await wait(50);
  check("limit visible to B", b.last.helpLimit === 2);
  await a.req("startGame");
  await wait(100);
  const byId = { [a.last.me.id]: a, [b.last.me.id]: b, [c.last.me.id]: c };
  const activeId = a.last.activeId;
  const active = byId[activeId];
  const others = Object.keys(byId).filter((id) => id !== activeId);
  const notActive = byId[others[0]];
  check("non-active cannot request help", !(await notActive.req("help:request", { playerId: activeId })).ok);
  check("cannot ask self", !(await active.req("help:request", { playerId: activeId })).ok);
  const r = await active.req("help:request", { playerId: others[0] });
  check("active requests help", r.ok);
  await wait(50);
  const st = active.last;
  check("help in state", st.help && st.help.askerId === activeId && st.help.helperId === others[0]);
  check("turn timer paused", st.turnRemainingMs === null);
  check("help ~60s", st.help.remainingMs > 58000);
  check("helpsLeft decremented", st.players.find((p) => p.id === activeId).helpsLeft === 1);
  check("second help while active fails", !(await active.req("help:request", { playerId: others[1] })).ok);
  const outsider = byId[others[1]];
  const hostIsOutsider = outsider === a;
  if (!hostIsOutsider) check("outsider non-host cannot end", !(await outsider.req("help:end")).ok);
  check("helper ends early", (await byId[others[0]].req("help:end")).ok);
  await wait(50);
  check("help cleared", active.last.help === null);
  check("turn timer restarted", active.last.turnRemainingMs > 44000);
  check("same player still active", active.last.activeId === activeId);
  await active.req("help:request", { playerId: others[1] });
  await wait(50);
  check("second help works", active.last.help !== null);
  check("guess during help ends help and starts vote", (await active.req("guess")).ok);
  await wait(50);
  check("help gone, vote on", active.last.help === null && active.last.vote !== null);
  for (const id of others) await byId[id].req("vote", { approve: false });
  await wait(50);
  check("no helps left -> request fails", !(await active.req("help:request", { playerId: others[0] })).ok);
  check("host sets limit mid-game", (await a.req("setHelpLimit", { limit: 3 })).ok);
  await wait(50);
  check("helpsLeft now 1", active.last.players.find((p) => p.id === activeId).helpsLeft === 1);
  await active.req("help:request", { playerId: others[0] });
  await wait(50);
  check("host can end help (admin)", (await a.req("help:end")).ok || a === active || a === byId[others[0]]);
  console.log(failed ? `${failed} FAILED` : "ALL PASSED");
  process.exit(failed ? 1 : 0);
})();

const { Registry } = require("../game.js");
let failed = 0;
const check = (name, cond) => { console.log(cond ? "OK  " : "FAIL", name); if (!cond) failed++; };
const attempt = (fn) => { try { fn(); return true; } catch (e) { return e.message; } };
const reg = new Registry();
const room = reg.createRoom();
const ps = ["Ania", "Bartek", "Celina"].map((n) => { const p = room.addPlayer(n); p.connected = true; return p; });
for (const p of ps) room.setWords(p, Array.from({ length: 10 }, (_, i) => p.nick + "w" + i));
room.setSetting(ps[0], "authorFree", 2);
room.setSetting(ps[0], "authorLimit", 3);
room.setSetting(ps[0], "authorCost", 1);
room.setSetting(ps[0], "helpFree", 1);
room.setSetting(ps[0], "helpCost", 2);
room.setSetting(ps[0], "passFree", 1);
room.setSetting(ps[0], "passPenalty", 1);
room.setHelpLimit(ps[0], 99);
room.start(ps[0]);
const a = room.getPlayer(room.activeId);
const other = room.players.find((p) => p !== a);
const me = () => room.viewFor(a).me;
check("view: author left 3, next free", me().authorLeft === 3 && me().nextAuthorCost === 0);
check("helps unlimited -> null", room.viewFor(a).players.find((p) => p.id === a.id).helpsLeft === null);
const scores = [];
room.revealAuthor(a); scores.push(a.score);
room.pass(a); scores.push(a.score);
room.revealAuthor(a); scores.push(a.score);
room.pass(a); scores.push(a.score);
check("next author now paid", me().nextAuthorCost === 1 && me().authorLeft === 1);
room.revealAuthor(a); scores.push(a.score);
check("author limit reached", me().authorLeft === 0);
room.pass(a);
check("4th reveal blocked", attempt(() => room.revealAuthor(a)) === "Wykorzystałeś już limit odkryć autora");
console.log("scores after: reveal free, pass free, reveal free, pass -1, reveal -1 =>", scores.join(", "));
check("score sequence 0,0,0,-1,-2", scores.join(",") === "0,0,0,-1,-2");
const before = a.score;
room.requestHelp(a, other.id); room.endHelp(a);
check("first help free", a.score === before);
room.requestHelp(a, other.id); room.endHelp(a);
check("second help costs 2", a.score === before - 2);
for (let i = 0; i < 5; i++) { room.requestHelp(a, other.id); room.endHelp(a); }
check("unlimited helps work (7 used)", a.helpsUsed === 7);
room.adminEndGame(ps[0]);
room.backToLobby(ps[0]);
room.setSetting(ps[0], "authorLimit", 0);
room.start(ps[0]);
check("author disabled", attempt(() => room.revealAuthor(room.getPlayer(room.activeId))) === "Odkrywanie autora jest wyłączone");
check("counters reset on new game", room.viewFor(a).me.nextAuthorCost === 0 && a.helpsUsed === 0);
console.log(failed ? failed + " FAILED" : "ALL PASSED");
process.exit(failed ? 1 : 0);
